#!/usr/bin/env node
// Build-time only. The production container executes these reviewed bytes; it
// never installs a dependency, reads a request-supplied module or runs a shell.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(resolve(root,'workers/scan-api/package.json'));
const {build}=require('esbuild');
const built=await build({entryPoints:[resolve(root,'workers/network-probe/src/website-content-collector.js')],bundle:true,platform:'node',format:'esm',target:'node22',write:false,minify:true,legalComments:'none',logLevel:'silent'});
const source=built.outputFiles[0].text.replace(/export\{([^}]+)\};?\s*$/,(_match,exports)=>{const name=exports.match(/([\w$]+) as runWebsiteContentCollector/)?.[1]||'runWebsiteContentCollector';return `const __runWebsiteContentCollector=${name};\n`;});
if(!source.includes('const __runWebsiteContentCollector='))throw new Error('missing_collector_export');
const output=`// Generated by scripts/build-website-content-program.js; do not edit.\nexport const WEBSITE_CONTENT_PROGRAM=${JSON.stringify(source)};\n`;
const target=resolve(root,'workers/network-probe/src/website-content-program.generated.js');
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==output)throw new Error('website_content_program_drift');console.log('Website content production bundle is current.');}else{writeFileSync(target,output);console.log('Built website content production bundle.');}
