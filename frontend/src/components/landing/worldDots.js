let cached = null

// Unit vectors [x0, y0, z0, x1, y1, z1, ...] of every land point.
export function landVectors() {
  if (cached) return cached
  const bytes = typeof atob === 'function'
    ? Uint8Array.from(atob(LAND_MASK), ch => ch.charCodeAt(0))
    : new Uint8Array(0)
  const out = []
  const golden = Math.PI * (3 - Math.sqrt(5))
  for (let i = 0; i < LAND_POINTS; i++) {
    if (!((bytes[i >> 3] >> (i & 7)) & 1)) continue
    const y = 1 - (2 * (i + 0.5)) / LAND_POINTS
    const r = Math.sqrt(1 - y * y)
    const a = golden * i
    out.push(Math.cos(a) * r, y, Math.sin(a) * r)
  }
  cached = new Float32Array(out)
  return cached
}
